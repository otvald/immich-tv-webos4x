#!/usr/bin/env node
import {copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync, rmSync} from 'node:fs';
import {basename, extname, join, resolve} from 'node:path';

const ROOT = resolve(new URL('..', import.meta.url).pathname);
const MP3_DIR = resolve(ROOT, 'mp3');
const GENERATED_DIR = resolve(ROOT, 'src/generated');
const MANIFEST_PATH = resolve(GENERATED_DIR, 'musicManifest.ts');
const DIST_MP3_DIR = resolve(ROOT, 'dist/mp3');
const COPY_TO_DIST = process.argv.includes('--copy-to-dist');

function jsString(value) {
	return JSON.stringify(value);
}

function fail(message) {
	console.error(`[generate-music-manifest] ERROR: ${message}`);
	process.exit(1);
}

const files = existsSync(MP3_DIR) ? readdirSync(MP3_DIR) : [];
const mp3Files = files.filter((file) => extname(file).toLowerCase() === '.mp3').sort((a, b) => a.localeCompare(b));
const licenseFiles = files.filter((file) => extname(file).toLowerCase() === '.license').sort((a, b) => a.localeCompare(b));
const licenseSet = new Set(licenseFiles);

for (const licenseFile of licenseFiles) {
	const trackName = basename(licenseFile, '.license');
	if (!files.includes(`${trackName}.mp3`)) {
		fail(`${licenseFile} has no matching ${trackName}.mp3`);
	}
}

const tracks = mp3Files.map((mp3File) => {
	const trackName = basename(mp3File, '.mp3');
	const licenseFile = `${trackName}.license`;
	if (!licenseSet.has(licenseFile)) {
		fail(`${mp3File} must have a matching nonempty ${licenseFile}`);
	}

	const licenseText = readFileSync(join(MP3_DIR, licenseFile), 'utf8').trim();
	if (!licenseText) {
		fail(`${licenseFile} must be nonempty`);
	}

	return {
		title: trackName,
		fileName: mp3File,
		url: `./mp3/${encodeURIComponent(mp3File)}`,
		licenseFileName: licenseFile,
		licenseText,
	};
});

mkdirSync(GENERATED_DIR, {recursive: true});
writeFileSync(
	MANIFEST_PATH,
	[
		'// Generated by tools/generate-music-manifest.mjs. Do not edit by hand.',
		'export interface MusicTrackManifestEntry {',
		'\ttitle: string;',
		'\tfileName: string;',
		'\turl: string;',
		'\tlicenseFileName: string;',
		'\tlicenseText: string;',
		'}',
		'',
		'export const musicTracks: MusicTrackManifestEntry[] = [',
		...tracks.map((track) => `\t{title: ${jsString(track.title)}, fileName: ${jsString(track.fileName)}, url: ${jsString(track.url)}, licenseFileName: ${jsString(track.licenseFileName)}, licenseText: ${jsString(track.licenseText)}},`),
		'];',
		'',
	].join('\n'),
	'utf8'
);

if (COPY_TO_DIST) {
	rmSync(DIST_MP3_DIR, {recursive: true, force: true});
	mkdirSync(DIST_MP3_DIR, {recursive: true});
	for (const track of tracks) {
		copyFileSync(join(MP3_DIR, track.fileName), join(DIST_MP3_DIR, track.fileName));
		copyFileSync(join(MP3_DIR, track.licenseFileName), join(DIST_MP3_DIR, track.licenseFileName));
	}
}

console.log(`[generate-music-manifest] ${tracks.length} licensed MP3 track(s)`);
console.log(`  Manifest: ${MANIFEST_PATH}`);
if (COPY_TO_DIST) console.log(`  Copied to: ${DIST_MP3_DIR}`);
